import { test, expect } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createOfflineModule } from '../../xhs-offline-skill/offline/index.mjs';
import { MockXhsAdapter } from '../../xhs-offline-skill/adapters/mockXhsAdapter.mjs';
import { lanAddresses } from '../../xhs-offline-skill/offline/mobileTransfer.mjs';
let root, module, pack;
test.beforeAll(async () => {
  root = await mkdtemp(path.join(os.tmpdir(), 'xhs-comments-browser-'));
  const adapter = new MockXhsAdapter({ total: 2, failures: false });
  const detail = adapter.getFeedDetail.bind(adapter);
  adapter.getFeedDetail = async preview => {
    const item = await detail(preview);
    item.comments[0].text = '<img src="https://example.com/evil" onerror="alert(1)">\n' + '评论长文。'.repeat(250);
    return item;
  };
  module = createOfflineModule({ dataDir: path.join(root, 'data'), adapter });
  pack = await module.prepare_offline({ targetMinutes: 30 });
});
test.afterAll(async () => { await rm(root, { recursive: true, force: true }); });
test('standalone downloaded file works offline with images and safe scrollable comments', async ({ browser }) => {
  const file = path.join(root, 'phone.html');
  await module.export_offline({ packId: pack.id, output: file, singleFile: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage(), remote = [], errors = [];
  page.on('request', r => { if (/^https?:/.test(r.url())) remote.push(r.url()); }); page.on('pageerror', e => errors.push(e.message));
  await context.setOffline(true); await page.goto(pathToFileURL(file).href);
  await expect(page.locator('#image')).not.toHaveJSProperty('naturalWidth', 0);
  await page.locator('#comments-toggle').click();
  await expect(page.locator('#comments-summary')).toContainText('已缓存 2 条');
  await expect(page.locator('.comment.reply')).toContainText('谢谢你');
  expect(await page.locator('#comments-list img').count()).toBe(0);
  await page.locator('#comments-panel').hover(); await page.mouse.wheel(0, 350);
  await expect(page.locator('#counter')).toHaveText('1 / 2');
  await page.locator('#comments-panel').focus(); await page.keyboard.press('ArrowDown');
  await expect(page.locator('#counter')).toHaveText('1 / 2');
  const client = await context.newCDPSession(page);
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 180, y: 450 }] });
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 180, y: 250 }] });
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect(page.locator('#counter')).toHaveText('1 / 2');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'output/playwright/offline-comments-mobile.png', fullPage: true });
  await page.locator('#next').click(); await expect(page.locator('#comments-panel')).toBeHidden();
  await page.reload(); await page.locator('#comments-toggle').click();
  await expect(page.locator('#counter')).toHaveText('2 / 2');
  await expect(page.locator('.comment.reply')).toBeVisible();
  expect(remote).toEqual([]); expect(errors).toEqual([]); await context.close();
});
test('offline reader restores position and font, searches comments and handles unavailable storage', async ({ browser }) => {
  const artifact = await module.deliver_offline({ packId: pack.id, output: path.join(root, 'reader-tools.html') });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await context.setOffline(true);
  const page = await context.newPage(), remote = [], errors = [];
  page.on('request', r => { if (/^https?:/.test(r.url())) remote.push(r.url()); }); page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(artifact.viewer).href);
  await page.locator('#next').click();
  const imageCount = await page.locator('#image-counter').textContent();
  if (Number(imageCount.split('/')[1]) > 1) await page.locator('#image-next').click();
  const image = await page.locator('#image-counter').textContent();
  await page.locator('#search-panel summary').click(); await page.locator('#font-toggle').click();
  await page.reload(); await expect(page.locator('#counter')).toHaveText('2 / 2');
  await expect(page.locator('#image-counter')).toHaveText(image); await expect(page.locator('body')).toHaveClass('large-text');
  await page.locator('#search-panel summary').click();
  await page.locator('#search').fill('谢谢你'); await expect(page.locator('#search-status')).toContainText('找到 2 条');
  await page.locator('#search').press('ArrowUp'); await expect(page.locator('#counter')).toHaveText('2 / 2');
  await page.locator('#search-results button').first().click(); await expect(page.locator('#counter')).toHaveText('1 / 2');
  await expect(page.locator('#search-panel')).not.toHaveAttribute('open', '');
  await page.locator('#search-panel summary').click(); await page.locator('#search').fill('无此关键词 xyz');
  await expect(page.locator('#search-status')).toContainText('找到 0 条');
  await page.locator('#search').fill(''); await expect(page.locator('#search-results button')).toHaveCount(0);
  await page.screenshot({ path: 'output/playwright/skill-reader-tools-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(remote).toEqual([]); expect(errors).toEqual([]); await context.close();
  const restricted = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await restricted.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('storage disabled'); } }); });
  await restricted.setOffline(true); const fallback = await restricted.newPage();
  await fallback.goto(pathToFileURL(artifact.viewer).href); await fallback.locator('#next').click();
  await fallback.locator('#search-panel summary').click(); await expect(fallback.locator('#resume-status')).toContainText('无法保存进度');
  await fallback.locator('#search-panel summary').click(); await fallback.locator('#comments-toggle').click();
  await expect(fallback.locator('.comment.reply')).toBeVisible(); await restricted.close();
});
test('QR reception downloads a file that reopens offline after computer transfer closes', async ({ page, context }) => {
  test.skip(!lanAddresses().length, 'No LAN interface');
  const transfer = await module.share_offline({ packId: pack.id });
  try {
    await page.goto(transfer.desktopUrl);
    await expect(page.locator('figure img').first()).not.toHaveJSProperty('naturalWidth', 0);
    await page.screenshot({ path: 'output/playwright/mobile-receive.png', fullPage: true });
    const waiting = page.waitForEvent('download'); await page.getByText('下载离线阅读文件', { exact: true }).click();
    const download = await waiting, file = path.join(root, 'downloaded.html'); await download.saveAs(file);
    await transfer.close(); await context.setOffline(true); await page.goto(pathToFileURL(file).href);
    await expect(page.locator('#image')).not.toHaveJSProperty('naturalWidth', 0);
    await page.locator('#comments-toggle').click(); await expect(page.locator('.comment.reply')).toContainText('谢谢你');
  } finally { if (transfer.server.listening) await transfer.close(); }
});
